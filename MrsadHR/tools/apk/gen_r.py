#!/usr/bin/env python3
"""Turns the aapt2 generated R.java into a Kotlin R object for the command line build.

Gradle generates its own R for the IDE build; this file is only used by tools/apk/build_apk.sh so
that the same Kotlin sources can be compiled with plain kotlinc.
"""
import re
import sys

src, dst = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8").read()

blocks = {}
for kind, body in re.findall(r"public static final class (\w+) \{(.*?)\n  \}", text, re.S):
    entries = re.findall(r"public static final int (\w+)\s*=\s*(0x[0-9a-fA-F]+|\d+);", body)
    if entries:
        blocks[kind] = entries

lines = ["// Generated by tools/apk/gen_r.py. Do not edit.", "package com.mrsadhr", "", "object R {"]
for kind, entries in sorted(blocks.items()):
    lines.append(f"    object {kind} {{")
    for name, value in entries:
        lines.append(f"        const val {name}: Int = {value}")
    lines.append("    }")
lines += ["}", ""]
open(dst, "w", encoding="utf-8").write("\n".join(lines))
print(f"R.kt: {sum(len(v) for v in blocks.values())} symbols in {len(blocks)} types")
