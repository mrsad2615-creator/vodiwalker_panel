#!/usr/bin/env python3
"""Generate a Kotlin `R` class from an Android module's res/ directory.

WHY THIS EXISTS
Gradle generates R from resources. Without Gradle, `R.font.vazirmatn_regular` and
`R.string.app_name` cannot resolve, and a typo in a resource name - the single most
common Android bug - is invisible to every other check in this repo.

So: parse the module's res/ folder for real, emit an R class with the ids it finds,
and compile the module against it. A reference to a resource that does not exist in
that module now FAILS the audit, exactly as it would fail under Gradle.

Usage: python3 tooling/gen_r.py <module-dir> <out-file> [<base-package>]
"""

from __future__ import annotations

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

RES_TYPES = {
    "anim": "anim",
    "animator": "animator",
    "color": "color",
    "dimen": "dimen",
    "drawable": "drawable",
    "font": "font",
    "layout": "layout",
    "menu": "menu",
    "mipmap": "mipmap",
    "navigation": "navigation",
    "raw": "raw",
    "string": "string",
    "style": "style",
    "values": "values",
    "xml": "xml",
}

NAME_RE = re.compile(r'name="([^"]+)"')


def collect(res_dir: Path) -> dict[str, set[str]]:
    """Returns {resource_type: {names}} parsed from the module's res/ tree."""
    found: dict[str, set[str]] = {}

    if not res_dir.is_dir():
        return found

    for folder in sorted(res_dir.iterdir()):
        if not folder.is_dir():
            continue
        # folder is e.g. "font", "values-fa", "drawable-nodpi"
        base_type = folder.name.split("-", 1)[0]

        # File-based resources: the file name is the resource name.
        if base_type in {"font", "drawable", "mipmap", "layout", "menu", "navigation", "raw", "anim", "animator", "xml"}:
            for entry in folder.iterdir():
                if entry.is_file() and not entry.name.startswith("."):
                    stem = entry.name.rsplit(".", 1)[0]
                    # 9-patch and density-qualified files: keep the stem as written.
                    found.setdefault(base_type, set()).add(stem)
            continue

        # Value resources: <resources><string name="x">...</string></resources>
        if base_type in {"values", "color", "dimen", "string", "style"}:
            for entry in folder.glob("*.xml"):
                try:
                    root = ET.parse(entry).getroot()
                except ET.ParseError:
                    # A malformed values file would break the real build too; report it
                    # loudly instead of silently generating an incomplete R.
                    print(f"WARN: {entry} is not well-formed XML", file=sys.stderr)
                    continue
                for child in root:
                    if not isinstance(child.tag, str):
                        continue
                    tag = child.tag.split("}")[-1]
                    if tag in {"item", "string", "color", "dimen", "style", "bool", "integer", "fraction", "plurals", "array", "string-array", "integer-array"}:
                        name = child.get("name")
                        if name:
                            rtype = "style" if tag == "style" else ("string" if tag == "string" else tag)
                            # `item type="string"` style declarations
                            if tag == "item":
                                itype = child.get("type")
                                if itype:
                                    rtype = itype
                            found.setdefault(rtype, set()).add(name.replace(".", "_"))

    return found


def emit(package: str, resources: dict[str, set[str]]) -> str:
    lines = [
        "// GENERATED by tooling/gen_r.py - do not edit, do not commit.",
        f"package {package}",
        "",
        "object R {",
    ]
    next_id = 0x7F010000
    for rtype in sorted(resources):
        names = sorted(resources[rtype])
        if not names:
            continue
        lines.append(f"    object {rtype} {{")
        for name in names:
            if not name.isidentifier():
                # Kotlin identifiers cannot start with a digit; Gradle would reject the
                # resource outright, so flag it rather than emitting invalid code.
                raise SystemExit(f"FATAL: resource name {name!r} is not a valid identifier")
            lines.append(f"        const val {name}: Int = {next_id}")
            next_id += 1
        lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def namespace_of(module_dir: Path) -> str | None:
    """Reads `namespace = "..."` from the module's build.gradle.kts."""
    gradle = module_dir / "build.gradle.kts"
    if not gradle.is_file():
        return None
    match = re.search(r'namespace\s*=\s*"([^"]+)"', gradle.read_text())
    return match.group(1) if match else None


def main() -> int:
    if len(sys.argv) < 3:
        print(__doc__, file=sys.stderr)
        return 2
    module_dir = Path(sys.argv[1])
    out_file = Path(sys.argv[2])
    package = sys.argv[3] if len(sys.argv) > 3 else namespace_of(module_dir)
    if not package:
        raise SystemExit(f"FATAL: no namespace in {module_dir}/build.gradle.kts and none given")

    resources = collect(module_dir / "src" / "main" / "res")
    out_file.parent.mkdir(parents=True, exist_ok=True)
    out_file.write_text(emit(package, resources))
    total = sum(len(v) for v in resources.values())
    types = ", ".join(f"{k}={len(v)}" for k, v in sorted(resources.items()))
    print(f"R: {total} ids ({types}) -> {out_file}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
