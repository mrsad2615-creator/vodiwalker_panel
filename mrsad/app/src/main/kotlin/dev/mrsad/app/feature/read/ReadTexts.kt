/**
 * Local reading corpus with comprehension questions authored for MRSAD.
 *
 * Each text has four questions whose answers are supported by the text itself —
 * no trivia, no confusion, and no copyrighted material.
 *
 * Texts carry a [level] (1 = آسان … 3 = دشوار) so the corpus can grow into a
 * progression rather than a flat list: the level describes the *density* of
 * the prose — shorter sentences and fewer clauses at level 1, denser
 * subordinate clauses at level 3 — and it is shown next to every title so the
