def st(name, **kw):
    return B.S(name, **kw)


def build_doc(path, title, story):
    doc = SimpleDocTemplate(path, pagesize=A4, leftMargin=M, rightMargin=M, topMargin=46,
                            bottomMargin=38, title=title, author="Science 8 Exam Guide")

    def hf(canvas, d):
        if d.page == 1:
            return
        canvas.saveState()
        canvas.setFont("Vazir", 8)
        canvas.setFillColor(HexColor("#6B7280"))
        canvas.drawCentredString(W / 2, H - 26, B.fa(title))
        canvas.line(M, H - 32, W - M, H - 32)
        canvas.setFont("Vazir", 9)
        canvas.drawCentredString(W / 2, 24, B.fa(f"صفحه {d.page}"))
        canvas.restoreState()

    doc.build(story, onFirstPage=hf, onLaterPages=hf)
    print("built", path)


